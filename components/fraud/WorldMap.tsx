'use client'

function ll(lon: number, lat: number) {
  return `${(((lon + 180) / 360) * 1000).toFixed(1)},${(((90 - lat) / 180) * 500).toFixed(1)}`
}

function p(...coords: [number, number][]) {
  return 'M ' + coords.map(([lon, lat]) => ll(lon, lat)).join(' L ') + ' Z'
}

function pos(lon: number, lat: number) {
  return {
    left: `${(((lon + 180) / 360) * 100).toFixed(2)}%`,
    top: `${(((90 - lat) / 180) * 100).toFixed(2)}%`,
  }
}

